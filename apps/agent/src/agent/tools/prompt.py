    " of control.\n"
    "- For closed-ended clarification questions, include 2-4 short choices in"
    " request_user_input. For exact values like email addresses or paragraph text, leave"
    " choices empty so the user can type the value.\n"
    "- When calling request_user_input, make the question self-contained and specific."
    " Ask for exactly one missing detail or decision at a time, and fill missing_fields"
    " with exactly one human-readable label for that current detail, such as"
