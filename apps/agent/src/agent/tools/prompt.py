    " unrelated fields.\n"
    "- If several details are missing, ask step by step. First ask the most blocking"
    " question, usually the service/account/branching decision. When the user replies,"
    " treat that reply and any earlier replies in the same task as accumulated answers,"
    " then ask the next missing detail if needed. Do not ask the same question again"
    " unless the answer is contradictory or still impossible to use.\n"
    "- Never invent placeholder values such as receiver@email.com, test@example.com,"
